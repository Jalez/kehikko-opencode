import { resolve } from 'node:path'

import tailwindcss from '@tailwindcss/vite'
import react from '@vitejs/plugin-react'
import { doors, originFor, serves } from 'kehikot-module-protocol/serve'
import { defineConfig, type Plugin } from 'vite'

import { BUILD, MANIFEST, MOST_READ, TICKET, answer, ours, servingAt, stream } from './doors.ts'
import { serveSessions } from './live.ts'
import { ID, PREFERRED_PORT } from './manifest.ts'

/**
 * The port this process actually ended up on, which is not knowable here:
 * `serves()` prefers `$PORT`, then `PREFERRED_PORT`, and moves to the next
 * free one when that is taken. It is corrected below, inside `listening`,
 * because the fence in `live.ts` accepts a handshake only when its `Origin`
 * and `Host` name the port this server is really on — a fence holding a stale
 * number refuses this module's own page.
 */
let bound = PREFERRED_PORT

/**
 * The socket, beside the doors and served by the one process that serves the
 * page. It needs Vite's own HTTP server, which is Vite's to give, so it is a
 * plugin of its own and not one of the protocol's doors. It cannot be a
 * second server: a module is ONE ORIGIN, and a socket on another port would
 * be outside the very origin check that holds the fence up.
 */
function sockets(): Plugin {
  return {
    name: 'codex-sessions',
    apply: 'serve',
    configureServer(server) {
      const http = server.httpServer
      if (!http) {
        server.config.logger.error('codex: no HTTP server to attach the session socket to. The container will load and no session will ever open.')
        return
      }
      http.once('listening', () => {
        const address = http.address()
        if (address && typeof address === 'object') bound = address.port
        /* The skills name the origin this module is really on, not the one it preferred (skills.ts). */
        servingAt(originFor(bound))
        serveSessions(http, bound, (line) => server.config.logger.info(line))
      })
    },
  }
}

/**
 * - `serves()` first: it claims the port and keeps the registration true.
 * - `doors()` serves the manifest, the page at `/app` (generated, with the
 *   ticket and this process's build printed into it), and `/healthz`, `/mcp`
 *   and `/api/*` through `answer` in doors.ts — `/api/feed` as a stream — and each offered
 *   skill's SKILL.md at `/kehikot/skills/<name>.md` (skills.ts).
 * - Loopback, explicitly, and `cors: false` written rather than omitted: the
 *   thing behind the ticket runs a program as the person, and the absence of
 *   a permissive header is what keeps a page in another tab from reading it.
 * - The page is generated by `doors()` here. `bun run build` compiles it for
 *   `serve.ts`, which `run.sh` starts instead when the build is this checkout's.
 */
export default defineConfig({
  base: './',
  plugins: [
    serves({ id: ID, prefer: PREFERRED_PORT }),
    sockets(),
    doors({ manifest: MANIFEST, answer, stream, build: BUILD, page: { title: 'Codex', ticket: TICKET }, maxBodyBytes: MOST_READ, ours }),
    react(),
    tailwindcss(),
  ],
  resolve: { alias: { '@': resolve(import.meta.dirname, 'src') } },
  server: {
    host: '127.0.0.1',
    cors: false,
  },
})
